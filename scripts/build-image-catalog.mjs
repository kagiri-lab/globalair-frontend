// Lists every website image (/site/...) with where it's used, for Settings → Website images.
// Run after adding or removing images in the code:  node scripts/build-image-catalog.mjs
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SRC = join(ROOT, 'src');
const OUT = join(SRC, 'lib', 'siteImageCatalog.ts');
const IMG = /['"(`](\/site\/[A-Za-z0-9_./-]+\.(?:jpe?g|png|webp|gif))/g;
const SKIP = new Set(['/site/logo1.png']); // brand logo: Settings → Branding

// Where a file's images appear on the site
const FILE_LABELS = {
    'app/(site)/page.tsx': 'Home page',
    'components/site/HeroSlider.tsx': 'Home slider',
    'components/site/PageHero.tsx': 'Page banners',
    'components/site/SiteFooter.tsx': 'Footer',
    'components/site/PromoPopup.tsx': 'Promo popup',
    'components/site/Sidebar.tsx': 'Sidebar',
    'components/portal/portal.css': 'Customer portal',
};
const CONTENT_LABELS = {
    HERO_SLIDES: 'Home slider', CLIENTS: 'Client logos', PARTNERS: 'Partners page', HOME_TESTIMONIALS: 'Home page',
    TESTIMONIALS: 'Testimonials page', GALLERY: 'Gallery', SERVICES: 'Service pages',
};
const pageLabel = (rel) => {
    const m = rel.match(/^app\/\(site\)\/([^/]+)/);
    if (!m) return FILE_LABELS[rel] || 'Other';
    const name = m[1].replace(/-/g, ' ');
    return `${name[0].toUpperCase()}${name.slice(1)} page`;
};
// Groups in the settings screen, by what the image is
const groupFor = (path) =>
    /\/(slides|parallax)\/|banner/.test(path) ? 'Banners & slider'
        : /\/client\//.test(path) ? 'Client & partner logos'
            : /\/portfolio\//.test(path) ? 'Gallery'
                : /\/services\//.test(path) ? 'Services'
                    : /\/(imagebox|blog)\//.test(path) ? 'Home page'
                        : /\/(about|img-single)\//.test(path) ? 'About & company'
                            : /promo/.test(path) ? 'Promo popup'
                                : 'Other';
// Large backgrounds keep more pixels than cards; logos and avatars need very few
const maxWidthFor = (path) =>
    /\/(slides|parallax)\/|banner|404/.test(path) ? 1920
        : /\/client\//.test(path) ? 480
            : /user\.|\/testimonials\//.test(path) ? 400
                : 1400;

const walk = (dir) => readdirSync(dir).flatMap(f => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|css)$/.test(f) ? [p] : [];
});

const found = new Map(); // path → { usedOn: Set, label }
for (const file of walk(SRC)) {
    const rel = relative(SRC, file);
    if (rel === 'lib/siteImageCatalog.ts') continue;
    const lines = readFileSync(file, 'utf8').split('\n');
    let exportName = null;
    lines.forEach(line => {
        const ex = line.match(/^export const ([A-Z_]+)/);
        if (ex) exportName = ex[1];
        for (const [, path] of line.matchAll(IMG)) {
            if (SKIP.has(path)) continue;
            const where = rel === 'lib/siteContent.ts' ? CONTENT_LABELS[exportName] || 'Website' : FILE_LABELS[rel] || pageLabel(rel);
            const title = line.match(/(?:title|name):\s*'([^']+)'/)?.[1];
            const entry = found.get(path) || { usedOn: new Set(), label: '' };
            entry.usedOn.add(where);
            if (title && !entry.label) entry.label = title;
            found.set(path, entry);
        }
    });
}

const items = [...found.entries()]
    .filter(([path]) => existsSync(join(ROOT, 'public', path)))
    .map(([path, e]) => ({
        path,
        label: e.label || path.split('/').pop(),
        group: groupFor(path),
        usedOn: [...e.usedOn],
        maxWidth: maxWidthFor(path),
    }))
    .sort((a, b) => a.group.localeCompare(b.group) || a.path.localeCompare(b.path));

writeFileSync(OUT, `// Generated by scripts/build-image-catalog.mjs: every website image staff can replace in Settings → Website images.
// Re-run the script after adding or removing images in the code.

export interface SiteImage { path: string; label: string; group: string; usedOn: string[]; maxWidth: number }

export const SITE_IMAGES: SiteImage[] = ${JSON.stringify(items, null, 4)};
`);
console.log(`${items.length} images in ${new Set(items.map(i => i.group)).size} groups → ${relative(ROOT, OUT)}`);
